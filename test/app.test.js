const {test,after}=require('node:test');
const assert=require('node:assert/strict');
const imap=require('../server/services/mail-imap');
let verified;
imap.verifyCredentials=async c=>{verified=c;if(c.password!=='test-only-password'){const e=new Error('Rejected');e.code='MAIL_AUTH';throw e;}};
imap.forget=()=>{};
imap.listFolders=async()=>[{path:'INBOX',name:'Inbox',role:'inbox',unread:0}];
const app=require('../server/server');
const server=app.listen(0,'127.0.0.1');
after(()=>new Promise(resolve=>server.close(resolve)));
test('standalone login, session boundary, origin checks and logout',async()=>{
 if(!server.listening)await new Promise(resolve=>server.once('listening',resolve));
 const base='http://127.0.0.1:'+server.address().port;
 const request=(url,options={})=>fetch(base+url,options);
 assert.equal((await request('/')).status,200);
 assert.equal((await request('/api/mail/folders')).status,401);
 const body=JSON.stringify({email:'test@stud.tu-darmstadt.de',username:'ab12cdef',password:'test-only-password'});
 assert.equal((await request('/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json',Origin:'https://untrusted.example'},body})).status,403);
 assert.equal((await request('/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json',Origin:base},body:JSON.stringify({email:'wrong',username:'ab12cdef',password:'test'})})).status,400);
 const login=await request('/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json',Origin:base},body});
 assert.equal(login.status,200);assert.equal(verified.username,'ab12cdef');
 const cookie=login.headers.get('set-cookie');assert.match(cookie,/HttpOnly/);assert.match(cookie,/SameSite=Strict/);assert.ok(!cookie.includes('test-only-password'));
 const headers={Cookie:cookie.split(';')[0],Origin:base};
 assert.equal((await request('/api/auth/me',{headers})).status,200);
 assert.equal((await request('/api/mail/folders',{headers})).status,200);
 assert.equal((await request('/api/mail/folders',{headers:{Cookie:'tu_mail_session=tampered'}})).status,401);
 assert.equal((await request('/api/mail/watch',{headers})).status,404);
 assert.equal((await request('/api/auth/logout',{method:'POST',headers})).status,200);
 assert.equal((await request('/api/mail/folders',{headers})).status,401);
});
